"""Generate crates/langdetect/src/tables.rs from langdetect 1.0.9 and str.isupper dumps.

Usage: python gen_tables.py OUT.rs UPPER_1.json [UPPER_2.json ...]
The dumps come from scripts/dump_uppercase.py run under each supported Python.
"""

import json
import sys

from langdetect.utils import unicode_block as ub
from langdetect.utils.ngram import NGram


def ranges(cps):
    out = []
    for c in sorted(cps):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def rust_char(c):
    return f"'\\u{{{ord(c):x}}}'"


def char_slice(s):
    return "&[" + ", ".join(rust_char(c) for c in s) + "]"


def main():
    out_path, dumps = sys.argv[1], sys.argv[2:]
    versions = {}
    for path in dumps:
        with open(path) as f:
            d = json.load(f)
        versions[d["unidata_version"]] = set(d["upper"])
    order = sorted(versions, key=lambda v: tuple(map(int, v.split("."))))
    latest = versions[order[-1]]
    for v in order:
        assert versions[v] <= latest, v

    lines = [
        "// Generated by scripts/gen_tables.py from langdetect 1.0.9 and CPython unicodedata.",
        "// Do not edit by hand.",
        "",
        "pub(crate) const BLOCKS: &[(u8, u32, u32)] = &[",
    ]
    lines += [f"    ({b}, 0x{s:X}, 0x{e:X})," for b, s, e in ub._unicode_blocks]
    lines.append("];")
    lines.append("")
    lines.append(f"pub(crate) const LATIN1_EXCLUDED: &[char] = {char_slice(NGram.LATIN1_EXCLUDED)};")
    lines.append(f"pub(crate) const VI_FROM: &[char] = {char_slice(NGram.TO_NORMALIZE_VI_CHARS)};")
    lines.append(f"pub(crate) const VI_MARKS: &[char] = {char_slice(NGram.DMARK_CLASS)};")
    lines.append("pub(crate) const VI_TO: &[&[char]] = &[")
    lines += [f"    {char_slice(s)}," for s in NGram.NORMALIZED_VI_CHARS]
    lines.append("];")
    lines.append("")
    cjk = sorted((ord(k), ord(v)) for k, v in NGram.CJK_MAP.items() if k != v)
    lines.append("pub(crate) const CJK_MAP: &[(u32, u32)] = &[")
    for i in range(0, len(cjk), 6):
        lines.append("    " + " ".join(f"(0x{k:X}, 0x{v:X})," for k, v in cjk[i : i + 6]))
    lines.append("];")
    lines.append("")
    lines.append(f'/// `str.isupper()` of CPython with Unicode {order[-1]}.')
    lines.append("pub(crate) const UPPER: &[(u32, u32)] = &[")
    rs = ranges(latest)
    for i in range(0, len(rs), 6):
        lines.append("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i : i + 6]))
    lines.append("];")
    lines.append("")
    lines.append("/// Code points in `UPPER` that are not uppercase in older Unicode versions.")
    lines.append("pub(crate) const NOT_UPPER_IN: &[(&str, &[u32])] = &[")
    for v in order[:-1]:
        missing = sorted(latest - versions[v])
        body = ", ".join(f"0x{c:X}" for c in missing)
        lines.append(f'    ("{v}", &[{body}]),')
    lines.append("];")
    lines.append(f'pub(crate) const LATEST_UNICODE: &str = "{order[-1]}";')
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


main()
